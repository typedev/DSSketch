"""
GtkSourceView language definition for .dssketch, generated from DSSketch's own tables.

The definition gives an editor instant highlighting without calling Python: it
knows the keywords, flags, registered axes and the standard labels. It cannot
know what the parser knows (the labels a sketch defines, which axis a line
belongs to), so an editor refines it with `tokenize()`.

Its style ids are the token types (`dssketch:axis-tag`, `dssketch:label` …), so
a style scheme styles both the same way.

The file ships as `data/dssketch.lang`. After changing the tables, regenerate it:

    python -m dssketch.gtksourceview --write
"""

import sys
from pathlib import Path
from typing import List
from xml.sax.saxutils import escape

from . import syntax

LANG_PATH = Path(__file__).parent / "data" / "dssketch.lang"

# Token type -> GtkSourceView default style (None: no default look)
_STYLE_MAP = {
    syntax.KEYWORD: "def:keyword",
    syntax.AXIS_NAME: "def:type",
    syntax.AXIS_TAG: "def:type",
    syntax.LABEL: "def:constant",
    syntax.NUMBER: "def:decimal",
    syntax.SOURCE: "def:identifier",
    syntax.GLYPH: "def:identifier",
    syntax.TEXT: "def:string",
    syntax.STRING: "def:string",
    syntax.FLAG: "def:preprocessor",
    syntax.VARIABLE: "def:special-constant",
    syntax.OPERATOR: "def:operator",
    syntax.PUNCTUATION: None,
    syntax.COMMENT: "def:comment",
    syntax.UNKNOWN: "def:error",
}

_FLAGS = ("base", "sparse", "elidable", "layer")
# Sections that hold indented lines; a line starting at column 0 ends them
# (a comment does not: the parser keeps the section across comment lines)
_SECTION_END = r"^(?=[^\s#])"
_NUMBER = r"(?<![\w.$-])-?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?(?![\w.])"


def _labels() -> List[str]:
    """Standard one-word labels: weight, width, and the discrete axes'"""
    found = []
    for tag in ("wght", "wdth", "ital", "slnt"):
        for name, _ in syntax._standard_labels(tag):
            if name not in found:
                found.append(name)
    return found


def _style_name(token_type: str) -> str:
    return token_type.replace("-", " ").capitalize()


def language_spec() -> str:
    """The language definition, in the 2.0 format GtkSourceView 4 and 5 read (tested with 5)"""
    axis_words = sorted(set(syntax._AXIS_ALIASES) | set(syntax._AXIS_ALIASES.values()))
    out = []
    w = out.append

    w('<?xml version="1.0" encoding="UTF-8"?>')
    w("<!-- Generated by dssketch.gtksourceview (run it with the write option); do not edit by hand. -->")
    w('<language id="dssketch" name="DSSketch" version="2.0" _section="Other">')
    w("  <metadata>")
    w('    <property name="mimetypes">text/x-dssketch</property>')
    w('    <property name="globs">*.dssketch;*.dss</property>')
    w('    <property name="line-comment-start">#</property>')
    w("  </metadata>")
    w("")
    w("  <styles>")
    for token_type in syntax.TOKEN_TYPES:
        target = _STYLE_MAP[token_type]
        map_to = f' map-to="{target}"' if target else ""
        w(f'    <style id="{token_type}" name="{_style_name(token_type)}"{map_to}/>')
    w("  </styles>")
    w("")
    w("  <definitions>")

    def match(cid, regex, style=None, groups=None, extra=""):
        """A one-line match; `groups` styles sub-patterns instead of the whole"""
        attr = f' style-ref="{style}"' if style else ""
        w(f'    <context id="{cid}"{attr}{extra}>')
        w(f"      <match>{escape(regex)}</match>")
        if groups:
            w("      <include>")
            for group, group_style in groups:
                w(f'        <context sub-pattern="{group}" style-ref="{group_style}"/>')
            w("      </include>")
        w("    </context>")

    # A comment starts at the first # outside a closed string
    # (utils/comments.py): a closed string may hold a #, an unclosed one stops
    # before it. ' opens a string only where a word cannot continue
    w('    <context id="comment" style-ref="comment" end-at-line-end="true" class="comment" class-disabled="no-spell-check">')
    w("      <start>#</start>")
    w("    </context>")
    match(
        "string", r'"[^"]*"|"[^"#]*|(?<![^\s\[\](){},:="@$<>&])\'(?:[^\']*\'|[^\'#]*)', "string",
        extra=' class="string" class-disabled="no-spell-check"',
    )

    # Document lines: keyword and value
    match(
        "document-line", r'^(family|suffix|path)\b(?:\s+([^#"\s](?:[^#"]*[^#"\s])?))?',
        groups=[(1, "keyword"), (2, "text")],
    )
    # @layer=name, @layer name; a quoted name is left to the string context
    match(
        "layer", r"(@layer)\b(?:\s*(=)?\s*([^\s\"'#=][^\s\"'#]*))?",
        groups=[(1, "flag"), (2, "punctuation"), (3, "text")],
    )
    w('    <context id="lang-line" end-at-line-end="true">')
    w("      <start>^(lang)\\b</start>")
    w("      <include>")
    w('        <context sub-pattern="1" where="start" style-ref="keyword"/>')
    w('        <context ref="comment"/>')
    w('        <context ref="lang-code"/>')
    w('        <context ref="inner-punctuation"/>')
    w("      </include>")
    w("    </context>")
    match("lang-code", r"[A-Za-z][A-Za-z0-9-]*", "text")
    match("flag", r"@(?:" + "|".join(_FLAGS) + r")\b", "flag")
    match("variable", r"\$[A-Za-z0-9_]*", "variable")
    match("inline-keyword", r"\b(?:discrete|binary)\b", "keyword")
    match("line-keyword", r"^\s+(skip|outputs)\b", groups=[(1, "keyword")])
    # axis=value (named source coordinates, avar2): the name is an axis
    match("assignment", r"\b([A-Za-z_][A-Za-z0-9_]*)(?=\s*=)", groups=[(1, "axis-tag")])
    match("assigned-label", r"(=)\s*([A-Za-z_][A-Za-z0-9_]*)\b", groups=[(1, "punctuation"), (2, "label")])
    w('    <context id="axis-word" style-ref="axis-tag">')
    for word in axis_words:
        w(f"      <keyword>{word}</keyword>")
    w("    </context>")
    match("custom-axis-tag", r"\b[A-Z][A-Z0-9_]{3,}\b", "axis-tag")
    w('    <context id="standard-label" style-ref="label">')
    for label in _labels():
        w(f"      <keyword>{escape(label)}</keyword>")
    w("    </context>")
    match("number", _NUMBER, "number")
    match("operator", r">=|<=|==|&&|[<>]", "operator")
    match("punctuation", r"[\[\](){},:=-]", "punctuation")
    # Inside brackets: never the closing one, which ends the bracket context
    match("inner-punctuation", r"[,:=-]", "punctuation")
    # Inside source coordinates and rule conditions any other word is a label
    match("any-label", r"\b[A-Za-z_][A-Za-z0-9_.]*\b", "label")

    common = [
        "comment", "string", "layer", "flag", "variable", "inline-keyword", "line-keyword",
        "assignment", "assigned-label", "axis-word", "custom-axis-tag", "standard-label",
        "number", "operator", "punctuation",
    ]

    def bracketed(cid, opening, closing, inner):
        """`[ ]` / `( )` on one line, with its own word rules"""
        w(f'    <context id="{cid}" end-at-line-end="true">')
        w(f'      <start>{escape(opening)}</start>')
        w(f'      <end>{escape(closing)}</end>')
        w("      <include>")
        w('        <context sub-pattern="0" where="start" style-ref="punctuation"/>')
        w('        <context sub-pattern="0" where="end" style-ref="punctuation"/>')
        for ref in inner:
            w(f'        <context ref="{ref}"/>')
        w("      </include>")
        w("    </context>")

    # [Regular, Upright]: labels; [wght=Regular] (named, avar2) is assignments
    bracketed(
        "coordinates", r"\[", r"\]",
        ["comment", "assignment", "assigned-label", "number", "inner-punctuation", "operator", "any-label"],
    )
    # (weight >= Bold && CONTRAST <= 50): axes, then labels
    bracketed(
        "condition", r"\(", r"\)",
        ["comment", "axis-word", "custom-axis-tag", "number", "operator", "inner-punctuation", "any-label"],
    )

    # Line forms that need the section to be read
    match(
        "axis-definition",
        r'^\s+([A-Za-z][A-Za-z0-9_ ]*?)\s+(?=[^\s#]*:|(?:discrete|binary)\b)',
        groups=[(1, "axis-tag")],
    )
    match(
        "mapping-label",
        r"^\s+(?:(-?\d+(?:\.\d+)?)\s+)?([A-Za-z_][^\s>:@#\"]*)(?=\s*(?:>|@|#|$))",
        groups=[(1, "number"), (2, "label")],
    )
    match("source-name", r'^\s+("[^"#]*"|[^\s\[#@"][^\[#@=]*?)(?=\s*(?:\[|@|#|$)|\s+[A-Za-z_]\w*\s*=)', groups=[(1, "source")])
    match(
        "rule-head", r"^\s+([^\s>(#][^>(#]*?)\s*(>)\s*([^\s(#]+)",
        groups=[(1, "glyph"), (2, "operator"), (3, "glyph")],
    )
    # Never at column 0: a word there is the next section, and an inner context
    # would take it before the section's end
    match("skip-label", r"(?<=\s)[A-Za-z_][A-Za-z0-9_]*\b", "label")

    def section(cid, header, inner, header_groups):
        w(f'    <context id="{cid}">')
        w(f"      <start>{escape(header)}</start>")
        w(f"      <end>{escape(_SECTION_END)}</end>")
        w("      <include>")
        for group, style in header_groups:
            w(f'        <context sub-pattern="{group}" where="start" style-ref="{style}"/>')
        for ref in inner:
            w(f'        <context ref="{ref}"/>')
        w("      </include>")
        w("    </context>")

    kw = [(1, "keyword"), (2, "keyword")]
    section("axes-section", r"^(axes)(?:\s+(hidden))?\b", ["comment", "axis-definition", "mapping-label"] + common, kw)
    # sources [wght, CONTRAST]: brackets right after the keyword list axes
    match("any-axis", r"\b[A-Za-z_][A-Za-z0-9_]*\b", "axis-tag")
    w('    <context id="axis-order" end-at-line-end="true">')
    w("      <start>" + escape(r"(?<=^sources)\s*\[") + "</start>")
    w("      <end>" + escape(r"\]") + "</end>")
    w("      <include>")
    w('        <context sub-pattern="0" where="start" style-ref="punctuation"/>')
    w('        <context sub-pattern="0" where="end" style-ref="punctuation"/>')
    w('        <context ref="inner-punctuation"/>')
    w('        <context ref="any-axis"/>')
    w("      </include>")
    w("    </context>")
    section(
        "sources-section", r"^(sources)\b()",
        ["axis-order", "comment", "source-name", "coordinates"] + common, kw,
    )
    section("rules-section", r"^(rules)\b()", ["comment", "rule-head", "condition"] + common, kw)
    section(
        "instances-section", r"^(instances)(?:\s+(auto|off))?\b",
        ["comment", "line-keyword", "skip-label"], kw,
    )
    section("avar2-section", r"^(avar2)(?:\s+(vars|matrix))?\b", ["coordinates"] + common, kw)

    w('    <context id="dssketch" class="no-spell-check">')
    w("      <include>")
    for ref in ["comment", "document-line", "lang-line", "axes-section", "sources-section", "rules-section",
                "instances-section", "avar2-section"] + common:
        w(f'        <context ref="{ref}"/>')
    w("      </include>")
    w("    </context>")
    w("  </definitions>")
    w("</language>")
    return "\n".join(out) + "\n"


def language_spec_path() -> str:
    """Path of the shipped definition, for GtkSource.LanguageManager's search path"""
    return str(LANG_PATH)


def main(argv=None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if args == ["--write"]:
        LANG_PATH.write_text(language_spec(), encoding="utf-8")
        print(f"wrote {LANG_PATH}")
    else:
        sys.stdout.write(language_spec())
    return 0


if __name__ == "__main__":
    sys.exit(main())
